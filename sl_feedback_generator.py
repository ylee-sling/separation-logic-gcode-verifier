Voxel = Tuple[int, int, int]
BoxTuple = Tuple[int, int, int, int, int, int]  # (x_min, x_max, y_min, y_max, z_min, z_max), inclusive
_BOX_FIELDS = ("x_min", "x_max", "y_min", "y_max", "z_min", "z_max")

# --------------------------------------------------------------------------------------
# Figure 5 template constants
# --------------------------------------------------------------------------------------
PROMPT_TITLE = "Autogenerated SL Feedback Prompt"
HEADER_SYSTEM_ERROR = "[System Error]"
HEADER_CONFLICT_DOMAIN = "[Conflict Domain]"
HEADER_DIRECTIVE = "[Actionable Directive]"

# Spatial Heap states that can own a voxel and so be the subject of a Spatial Data Race.
# "Empty" is excluded because claiming an Empty voxel never violates the separating
# conjunction.
_VIOLABLE_RESOURCES = {"tool": "Tool", "environment": "Environment", "stock": "Stock"}

# The closing hint of Figure 5, used verbatim when no more specific hint applies.
_PAPER_HINT = (
    "Consider increasing the Z-axis clearance height (G00 Z...) prior to lateral XY translation."
)

# Deterministic hints keyed by (motion mode, violated resource). A key of (None, resource)
# matches any motion mode. The cases follow the fault sets of the operational semantics:
#   F_G00: V_path touches Environment or Stock  (rapids must stay in Empty space)
#   F_G01: V_path touches Environment           (cutting may consume Stock)
#   Tool : multi-tool CSL race, i.e. another thread owns the voxels.
_DIRECTIVE_HINTS = {
    ("G00", "Environment"): _PAPER_HINT,
    ("G00", "Stock"): (
        "G00 rapid positioning may only traverse Empty space: retract above the stock "
        "(G00 Z...) before lateral XY translation, and use G01 with a feed rate (F) for "
        "any move that enters the stock."
    ),
    ("G01", "Environment"): (
        "The Environment is non-machinable: retract to a safe Z height (G00 Z...), "
        "translate laterally clear of the conflict bounds, then re-approach and resume the cut."
    ),
    (None, "Tool"): (
        "These voxels are owned by another tool. Delay this motion until that tool has "
        "retracted from the shared region, or route around it."
    ),
}

# The conflict voxels come from the epsilon-padded swept volume (V_path = path ⊕ V_tool ⊕ B_ε).
# This note keeps the LLM from moving only the tool-center line to the edge of the box,
# which would cause the same collision again.
_ENVELOPE_NOTE = (
    "The bounds apply to the full tool envelope (tool geometry dilated by the safety margin ε); "
    "moving only the programmed tool-center coordinates to the edge of the bounds is not sufficient."
)

# --------------------------------------------------------------------------------------
# G-code text helpers
# --------------------------------------------------------------------------------------
_COMMENT = re.compile(r"\([^)]*\)|;.*$")
_N_WORD_PREFIX = re.compile(r"^\s*N\d+(?!\d)", re.IGNORECASE)
_BLOCK_NUMBER = re.compile(r"^\s*N?(\d+)\s*$", re.IGNORECASE)
# Motion words G0/G00 to G3/G03. Rejects G17, G28, G90 and similar, and fractional G-codes such as G1.1.
_MOTION_WORD = re.compile(r"G0*([0-3])(?![0-9.])", re.IGNORECASE)


def _detect_motion_mode(text: str) -> Optional[str]:
    """Return the canonical motion mode ("G00".."G03") named in a block, or None."""
    match = _MOTION_WORD.search(_COMMENT.sub(" ", text))
    return f"G0{match.group(1)}" if match else None


def _canonical_resource(value: str) -> str:
    key = str(value).strip().lower()
    if key not in _VIOLABLE_RESOURCES:
        raise ValueError(
            f"violated_resource must be one of {sorted(_VIOLABLE_RESOURCES.values())}, "
            f"got {value!r}. 'Empty' can never be the subject of a Spatial Data Race."
        )
    return _VIOLABLE_RESOURCES[key]


def _normalize_voxels(voxels: Iterable[Sequence[int]]) -> Tuple[Voxel, ...]:
    """Check that every voxel lies in Z^3, then return a sorted, de-duplicated tuple.

    Non-integer components are rejected. The Parser-Prover Handshake requires the Store to
    be fully exhausted before the proof phase, so a float here means a continuous value
    slipped past S_grid.
    """
    normalized = set()
    for index, voxel in enumerate(voxels):
        try:
            coords = tuple(voxel)
        except TypeError:
            raise TypeError(
                f"conflict_voxels[{index}] is not a coordinate triple: {voxel!r}"
            ) from None
        if len(coords) != 3:
            raise ValueError(
                f"conflict_voxels[{index}] must have exactly 3 components (x, y, z), got {voxel!r}"
            )
        for component in coords:
            if isinstance(component, bool) or not isinstance(component, Integral):
                raise TypeError(
                    f"conflict_voxels[{index}] = {voxel!r} has a non-integer component "
                    f"{component!r}. The SL Prover works on Z^3 only; continuous values "
                    f"must be discretized by the Parser (S_grid) first."
                )
        normalized.add((int(coords[0]), int(coords[1]), int(coords[2])))
    return tuple(sorted(normalized))


def _normalize_boxes(boxes: Iterable[object]) -> Tuple[BoxTuple, ...]:
    """Accept box objects with x_min..z_max attributes (e.g. cad_extractor.GridBox, by duck
    typing so this module stays import-free) or plain 6-tuples. Return sorted, de-duplicated
    integer tuples."""
    normalized = set()
    for index, box in enumerate(boxes):
        if all(hasattr(box, name) for name in _BOX_FIELDS):
            coords = tuple(getattr(box, name) for name in _BOX_FIELDS)
        else:
            try:
                coords = tuple(box)  # type: ignore[arg-type]
            except TypeError:
                raise TypeError(f"conflict_boxes[{index}] is not a box: {box!r}") from None
        if len(coords) != 6:
            raise ValueError(
                f"conflict_boxes[{index}] must be (x_min, x_max, y_min, y_max, z_min, z_max), got {box!r}"
            )
        for component in coords:
            if isinstance(component, bool) or not isinstance(component, Integral):
                raise TypeError(f"conflict_boxes[{index}] = {box!r} has a non-integer bound {component!r}")
        x0, x1, y0, y1, z0, z1 = (int(c) for c in coords)
        if x0 > x1 or y0 > y1 or z0 > z1:
            raise ValueError(f"conflict_boxes[{index}] has inverted bounds: {box!r}")
        normalized.add((x0, x1, y0, y1, z0, z1))
    return tuple(sorted(normalized))


