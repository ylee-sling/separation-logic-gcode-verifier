@dataclass(frozen=True)
class ConflictRecord:
    """A Spatial Data Race, as reported by the SL Prover.

    Required fields
    ---------------
    line_number       : Block number of the offending instruction, e.g. "N30" (an int is
                        accepted and becomes "N<int>").
    command           : Raw G-code text of the block, e.g. "G00 X9.0".
    conflict_voxels   : V_conflict = dom(h_swept) ∩ dom(h_env), as any iterable of integer
                        (x, y, z) triples. A list, a set or an (N, 3) integer numpy array all
                        work. Stored sorted and de-duplicated.
    violated_resource : Spatial Heap state that already owns the voxels: "Environment",
                        "Stock" or "Tool".
    multiplier        : Grid multiplier μ ∈ Z+ used by S_grid(x) = ⌊x·μ⌋.

    Optional fields
    ---------------
    resource_label    : Name of the specific obstacle, e.g. "Clamp" or "Clamp_1".
    motion_mode       : Active motion mode ("G0"/"G00", "G1"/"G01", ...). Set this for modal
                        blocks such as a bare "X20.0", which carry no G word. If left as None,
                        the mode is read from `command`.
    refine_window     : Explicit (first, last) block numbers for the regeneration directive.
                        If None, it is derived as N ± block_step.
    conflict_boxes    : V_conflict as a union of inclusive boxes (set by from_boxes()). When
                        present, every entry of conflict_voxels must lie inside one of them.
    """

    line_number: str
    command: str
    conflict_voxels: Tuple[Voxel, ...]
    violated_resource: str
    multiplier: int
    resource_label: Optional[str] = None
    motion_mode: Optional[str] = None
    refine_window: Optional[Tuple[str, str]] = None
    conflict_boxes: Optional[Tuple[BoxTuple, ...]] = None

    @classmethod
    def from_boxes(
        cls,
        line_number: str,
        command: str,
        conflict_boxes: Iterable[object],
        violated_resource: str,
        multiplier: int,
        **optional: object,
    ) -> "ConflictRecord":
        """Build a record from V_conflict given as boxes, e.g. the SL Prover's box intersections.

        `conflict_voxels` is set to the two opposite corners of every box. Those are genuine
        conflict voxels, and they span exactly the bounding box of the full union, which is
        all that B_conflict (Eq. 11) needs.
        """
        boxes = _normalize_boxes(conflict_boxes)
        if not boxes:
            raise ValueError("conflict_boxes is empty, so there is no Spatial Data Race to report.")
        corners = [corner for x0, x1, y0, y1, z0, z1 in boxes for corner in ((x0, y0, z0), (x1, y1, z1))]
        return cls(line_number, command, corners, violated_resource, multiplier,
                   conflict_boxes=boxes, **optional)  # type: ignore[arg-type]

    @property
    def bounding_box(self) -> "ConflictBox":
        """B_conflict for this record (Eq. 11)."""
        return _bbox_of(self.conflict_voxels)

    def __post_init__(self) -> None:
        line = self.line_number
        if isinstance(line, Integral) and not isinstance(line, bool):
            line = f"N{int(line)}"
        object.__setattr__(self, "line_number", str(line).strip())
        object.__setattr__(self, "command", str(self.command).strip())

        mu = self.multiplier
        if isinstance(mu, bool) or not isinstance(mu, Integral) or mu <= 0:
            raise ValueError(f"multiplier μ must be a positive integer (μ ∈ Z+), got {mu!r}")
        object.__setattr__(self, "multiplier", int(mu))

        object.__setattr__(self, "violated_resource", _canonical_resource(self.violated_resource))

        voxels = _normalize_voxels(self.conflict_voxels)
        if not voxels:
            raise ValueError(
                "conflict_voxels is empty. V_conflict = ∅ means the separating conjunction "
                "holds, so there is no Spatial Data Race to report."
            )
        object.__setattr__(self, "conflict_voxels", voxels)

        if self.motion_mode is not None:
            mode = _detect_motion_mode(str(self.motion_mode))
            if mode is None:
                raise ValueError(f"motion_mode must be one of G00-G03, got {self.motion_mode!r}")
            object.__setattr__(self, "motion_mode", mode)

        if self.refine_window is not None:
            first, last = self.refine_window
            object.__setattr__(self, "refine_window", (str(first).strip(), str(last).strip()))

        if self.conflict_boxes is not None:
            boxes = _normalize_boxes(self.conflict_boxes)
            if not boxes:
                raise ValueError("conflict_boxes, when given, must contain at least one box")
            for voxel in voxels:
                if not any(
                    b[0] <= voxel[0] <= b[1] and b[2] <= voxel[1] <= b[3] and b[4] <= voxel[2] <= b[5]
                    for b in boxes
                ):
                    raise ValueError(f"conflict voxel {voxel} lies outside every conflict box")
            object.__setattr__(self, "conflict_boxes", boxes)

    @property
    def effective_motion_mode(self) -> Optional[str]:
        """The explicit motion_mode if one was given, otherwise the G word found in the command."""
        return self.motion_mode or _detect_motion_mode(self.command)


def _cell_lower_mm(index: int, mu: int, decimals: int) -> Decimal:
    """Lower mm edge of grid cell `index` (index/μ), rounded toward -∞."""
    scaled = (index * 10 ** decimals) // mu
    return Decimal(scaled).scaleb(-decimals)


def _cell_upper_mm(index: int, mu: int, decimals: int) -> Decimal:
    """Upper mm edge of grid cell `index` ((index+1)/μ), rounded toward +∞."""
    scaled = -((-(index + 1) * 10 ** decimals) // mu)
    return Decimal(scaled).scaleb(-decimals)


@dataclass(frozen=True)
class ConflictBox:
    """B_conflict: the minimal axis-aligned box in Z^3 that encloses V_conflict (Eq. 11)."""

    x_min: int
    x_max: int
    y_min: int
    y_max: int
    z_min: int
    z_max: int

    def axes(self) -> Tuple[Tuple[str, int, int], ...]:
        return (
            ("X", self.x_min, self.x_max),
            ("Y", self.y_min, self.y_max),
            ("Z", self.z_min, self.z_max),
        )

    def grid_bounds_str(self) -> str:
        """Integer bounds in the Figure 5 notation, e.g. 'X ∈ [45, 55], Y ∈ [45, 55], Z ∈ [-10, 0]'."""
        return ", ".join(f"{axis} ∈ [{lo}, {hi}]" for axis, lo, hi in self.axes())

    def machine_bounds(self, mu: int, decimals: int = 3) -> Tuple[Tuple[Decimal, Decimal], ...]:
        """Per-axis (lower, upper) bounds in mm, rounded outward to `decimals` places."""
        if isinstance(mu, bool) or not isinstance(mu, Integral) or mu <= 0:
            raise ValueError(f"multiplier μ must be a positive integer, got {mu!r}")
        if decimals < 0:
            raise ValueError(f"decimals must be >= 0, got {decimals!r}")
        return tuple(
            (_cell_lower_mm(lo, mu, decimals), _cell_upper_mm(hi, mu, decimals))
            for _, lo, hi in self.axes()
        )

    def machine_bounds_str(self, mu: int, decimals: int = 3) -> str:
        bounds = self.machine_bounds(mu, decimals)
        return ", ".join(
            f"{axis} ∈ [{lo:f}, {hi:f}]"
            for (axis, _, _), (lo, hi) in zip(self.axes(), bounds)
        )


def _bbox_of(voxels: Sequence[Voxel]) -> ConflictBox:
    if not voxels:
        raise ValueError("cannot bound an empty conflict set")
    xs, ys, zs = zip(*voxels)
    return ConflictBox(min(xs), max(xs), min(ys), max(ys), min(zs), max(zs))


def compute_conflict_bbox(voxels: Iterable[Sequence[int]]) -> ConflictBox:
    """Compress V_conflict into the minimal axis-aligned bounding box B_conflict (Eq. 11)."""
    return _bbox_of(_normalize_voxels(voxels))


# --------------------------------------------------------------------------------------
# Prompt rendering
# --------------------------------------------------------------------------------------
def _instruction_line(record: ConflictRecord) -> str:
    """The offending block as in Figure 5 ('N045 G01 X50.0 ...'), without a duplicated N word."""
    if not record.line_number or _N_WORD_PREFIX.match(record.command):
        return record.command
    return f"{record.line_number} {record.command}"


def _refine_window(record: ConflictRecord, block_step: int) -> Optional[Tuple[str, str]]:
    """Block range to regenerate. Keeps the zero-padding of the original N word (N045 -> N035/N055)."""
    if record.refine_window is not None:
        return record.refine_window
    match = _BLOCK_NUMBER.match(record.line_number)
    if not match:
        return None
    digits = match.group(1)
    number, width = int(digits), len(digits)
    first = max(0, number - block_step)
    last = number + block_step
    return f"N{first:0{width}d}", f"N{last:0{width}d}"


def generate_sl_feedback(
    record: ConflictRecord,
    *,
    block_step: int = 10,
    mm_decimals: int = 3,
) -> str:
    """Render the Figure 5 "Autogenerated SL Feedback Prompt" for a Spatial Data Race.

    Parameters
    ----------
    record      : The conflict reported by the SL Prover.
    block_step  : N-word increment used to derive the regeneration window when
                  `record.refine_window` is not set. The default of 10 matches the N10/N20/N30
                  numbering of the case studies. Figure 5's N040..N050 window around N045
                  corresponds to block_step=5.
    mm_decimals : Decimal places for the back-projected mm bounds (rounded outward).

    Returns
    -------
    A multi-line string containing [System Error], [Conflict Domain] and
    [Actionable Directive], ready to append to the LLM context window.
    """
    if not isinstance(record, ConflictRecord):
        raise TypeError(f"expected ConflictRecord, got {type(record).__name__}")
    if isinstance(block_step, bool) or not isinstance(block_step, Integral) or block_step <= 0:
        raise ValueError(f"block_step must be a positive integer, got {block_step!r}")

    box = _bbox_of(record.conflict_voxels)
    mu = record.multiplier
    resource = record.violated_resource

    heap_description = f"{resource} Heap"
    if record.resource_label:
        heap_description += f" ({record.resource_label})"

    window = _refine_window(record, block_step)
    if window is not None:
        regenerate = f"Regenerate the toolpath between lines {window[0]} and {window[1]}."
    else:
        regenerate = "Regenerate the toolpath surrounding the instruction above."

    mode = record.effective_motion_mode
    hint = (
        _DIRECTIVE_HINTS.get((mode, resource))
        or _DIRECTIVE_HINTS.get((None, resource))
        or _PAPER_HINT
    )

    lines = [
        PROMPT_TITLE,
        f"{HEADER_SYSTEM_ERROR} Spatial Data Race Detected",
        "The Separation Logic verifier encountered a physical collision at the following instruction:",
        _instruction_line(record),
        "",
        HEADER_CONFLICT_DOMAIN,
        "The requested swept volume intersects with the restricted "
        f"{heap_description} within the following integer bounds:",
        box.grid_bounds_str(),
        f"Back-projected machine bounds (mm, μ = {mu}; grid cell i spans [i/μ, (i+1)/μ), "
        "rounded outward):",
        box.machine_bounds_str(mu, mm_decimals),
        "",
        HEADER_DIRECTIVE,
        f"{regenerate} You must route the tool to strictly avoid the stated conflict bounds.",
        _ENVELOPE_NOTE,
        hint,
    ]
    return "\n".join(lines)


