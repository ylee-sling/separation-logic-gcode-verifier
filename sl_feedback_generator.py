#!/usr/bin/env python3
"""
sl_feedback_generator.py -- The Refiner
=======================================

Step 4 of the Neuro-Symbolic Evaluator-Refiner pipeline
(Lee, "Correct-by-Construction G-Code Generation: A Neuro-Symbolic Approach via
Separation Logic", Sec. 5.2, Figure 5).

When the SL Prover cannot form the disjoint union  h_swept ⊎ h_env  (the separating
conjunction fails), it passes this module a ConflictRecord. This module then:

  1. Compresses the conflict set
         V_conflict = dom(h_swept) ∩ dom(h_env)                                (Eq. 10)
     into the minimal axis-aligned bounding box
         B_conflict = [x_min, x_max] × [y_min, y_max] × [z_min, z_max]          (Eq. 11)
  2. Renders the natural-language feedback prompt of Figure 5, using the headers
     [System Error], [Conflict Domain] and [Actionable Directive].

The output depends only on the record. There is no randomness, clock or I/O, and the
order of the voxels does not matter, so the same Spatial Data Race always produces the
same prompt.

Back-projection to machine units
--------------------------------
The Parser discretizes with S_grid(x) = ⌊x·μ⌋ (Lee, "Separation Logic for Verifying
Physical Collisions of CNC Programs", Sec. 4.2). Grid index i therefore represents the
half-open cell [i/μ, (i+1)/μ), and B_conflict covers the continuous region

    [x_min/μ, (x_max+1)/μ] × [y_min/μ, (y_max+1)/μ] × [z_min/μ, (z_max+1)/μ]   (mm)

Lower bounds are rounded toward -∞ and upper bounds toward +∞. The mm box given to the
LLM therefore always contains the region the Prover rejected. Using x_max/μ for the upper
bound would under-report the obstacle by one cell width.

Interface contract
------------------
sl_prover.py builds a ConflictRecord, and main_loop.py appends generate_sl_feedback(record)
to the LLM context. This module imports neither, so the dependency graph stays acyclic.

The prover stores footprints and obstacles as boxes, so it builds records with
ConflictRecord.from_boxes(). V_conflict is then the union of `conflict_boxes`. B_conflict
depends only on extreme coordinates, so the record keeps each box's two opposite corners as
`conflict_voxels`: real conflict voxels spanning exactly the same bounding box, so millions
of voxels never need to be listed.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from decimal import Decimal
from numbers import Integral
from typing import Iterable, Optional, Sequence, Tuple

