if __name__ == "__main__":
    import dataclasses
    import math

    MU = 10

    def s_grid(value_mm: float) -> int:
        """S_grid(x) = ⌊x·μ⌋ (Paper 1, Sec. 4.2). Uses Decimal so that e.g. 2.3·10 floors to 23, not 22."""
        return math.floor(Decimal(str(value_mm)) * MU)

    # Paper 1, Sec. 7.3 Scenario B, scaled by μ = 10. After the N20 cut the tool rests at
    # X6.0, and N30 commands a rapid to X9.0, straight into a clamp spanning X ∈ [8.0, 9.0]
    # at Y = 0, Z = 0. A point tool with ε = 0 keeps the mock one-dimensional, as in the paper.
    x_start, x_target = s_grid(6.0), s_grid(9.0)
    swept = {(x, 0, 0) for x in range(min(x_start, x_target), max(x_start, x_target) + 1)}
    clamp = {(x, 0, 0) for x in range(s_grid(8.0), s_grid(9.0) + 1)}
    conflict_voxels = sorted(swept & clamp)  # V_conflict = dom(h_swept) ∩ dom(h_env)  (Eq. 10)

    record = ConflictRecord(
        line_number="N30",
        command="G00 X9.0",
        conflict_voxels=conflict_voxels,
        violated_resource="Environment",
        multiplier=MU,
        resource_label="Clamp",
    )

    prompt = generate_sl_feedback(record)
    print(prompt)

    # ---- Self-checks -----------------------------------------------------------------
    assert compute_conflict_bbox(record.conflict_voxels) == ConflictBox(80, 90, 0, 0, 0, 0)
    for header in (HEADER_SYSTEM_ERROR, HEADER_CONFLICT_DOMAIN, HEADER_DIRECTIVE):
        assert prompt.count(header) == 1, f"header {header!r} must appear exactly once"
    assert "N30 G00 X9.0" in prompt
    assert "X ∈ [80, 90], Y ∈ [0, 0], Z ∈ [0, 0]" in prompt
    assert "X ∈ [8.000, 9.100], Y ∈ [0.000, 0.100], Z ∈ [0.000, 0.100]" in prompt
    assert "between lines N20 and N40" in prompt
    assert _PAPER_HINT in prompt
    # The prompt must not depend on voxel order.
    shuffled = dataclasses.replace(record, conflict_voxels=list(reversed(conflict_voxels)))
    assert generate_sl_feedback(shuffled) == prompt
    # Floor semantics on negative coordinates (NIST CTC fixtures sit near X = -245 mm, Z = -100 mm).
    assert (
        compute_conflict_bbox([(-2450, 0, -1000)]).machine_bounds_str(MU)
        == "X ∈ [-245.000, -244.900], Y ∈ [0.000, 0.100], Z ∈ [-100.000, -99.900]"
    )
    # Figure 5's own numbering: N045 with block_step=5 gives N040..N050.
    fig5 = ConflictRecord("N045", "G01 X50.0 Y50.0 Z-5.0", [(45, 45, -10), (55, 55, 0)], "Environment", 1)
    assert "between lines N040 and N050" in generate_sl_feedback(fig5, block_step=5)
    # Box-based records (used by sl_prover.py) render the same prompt as the voxel list.
    from_boxes = ConflictRecord.from_boxes(
        "N30", "G00 X9.0", [(80, 85, 0, 0, 0, 0), (84, 90, 0, 0, 0, 0)], "Environment", MU,
        resource_label="Clamp",
    )
    assert from_boxes.bounding_box == ConflictBox(80, 90, 0, 0, 0, 0)
    assert generate_sl_feedback(from_boxes) == prompt

    print("\n[self-check] all assertions passed")
